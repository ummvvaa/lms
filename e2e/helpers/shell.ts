/**
 * Локаторы оболочки: одно место на все прогоны.
 *
 * `<nav>` в разметке не один. С фазы 51 на телефоне вместо бокового меню
 * рисуется нижний бар — тоже `<nav>`, и он лежит в разметке на любой
 * ширине, а прячется стилями. Поэтому `page.locator("nav")` находит два
 * элемента и падает на strict mode (дефект D28): проверка обрывалась,
 * не дойдя до того, ради чего писалась.
 *
 * Локатор здесь один и назван по смыслу: следующая правка раскладки
 * чинится в одном файле, а не в каждом прогоне по очереди.
 */
import type { Locator, Page } from "@playwright/test";

/** Боковое меню на ноутбуке — то, где живут разделы роли. */
export function sidebar(page: Page): Locator {
  return page.locator("nav.shell__menu");
}
