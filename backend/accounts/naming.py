"""Имена учётных записей: что в них писать нельзя.

Учётная запись с именем «Салтанат (тест)» однажды остаётся в системе
насовсем: её видно в шапке, в журнале правок, в списке получателей письма
и в подписи под изменением. Отличить её от настоящей потом нечем —
и школа живёт с полудюжиной призраков в реестре.

Поэтому пометка проверяется на входе, в одном месте, и одинаково для
интерфейса администратора и для команды создания учётных записей.
"""

from __future__ import annotations

import re

#: Слова-пометки. Ищем по корню и с любой стороны от него: «тест»,
#: «(тест)», «Тестовый», «test», «demo», «разработка».
MARKERS = (
    "тест",
    "демо",
    "разработ",
    "заглуш",
    "test",
    "demo",
    "dummy",
    "sample",
    "fake",
)

MESSAGE = (
    "В имени пользователя нельзя писать «{word}»: такая запись останется "
    "в журнале правок и в письмах навсегда. Заведите человека под его "
    "настоящим именем, а для проверок используйте отдельный контур"
)


class NameRejected(ValueError):
    """Имя с пометкой заглушки. Текст читает человек в интерфейсе."""


def marker_in(full_name: str) -> str | None:
    """Найденная пометка или `None`. Регистр и окончания не важны."""
    lowered = re.sub(r"[\s\W_]+", " ", full_name.lower())
    for marker in MARKERS:
        if marker in lowered:
            return marker
    return None


def check_full_name(full_name: str) -> str:
    """Проверить имя перед сохранением. Пустое имя допустимо: его дозаполнят."""
    name = (full_name or "").strip()
    found = marker_in(name)
    if found is not None:
        raise NameRejected(MESSAGE.format(word=found))
    return name
