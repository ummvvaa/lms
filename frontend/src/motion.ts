/**
 * Движение: одни и те же длительности и кривые на весь интерфейс.
 *
 * Числа те же, что в `styles/motion.css`, — просто CSS-переменную
 * нельзя передать в `motion`, а два разных набора значений разъехались
 * бы в первую же правку. Ограничения фазы 32: ничего длиннее 320 мс,
 * никаких пружин в таблицах.
 *
 * `useReducedMotion()` спрашивает системную настройку «уменьшить
 * движение». При ней всё работает так же, просто без перехода:
 * строка встаёт на новое место сразу, а не едет.
 */
import { useReducedMotion } from 'motion/react'

/** Секунды — так их принимает `motion`. */
export const DURATION = { fast: 0.12, base: 0.18, slow: 0.26 } as const

/** Выход быстрый, вход мягкий — та же кривая, что у `--ease-out`. */
export const EASE = [0.22, 0.61, 0.36, 1] as const

/**
 * Переезд строк при сортировке и фильтрации — главный эффект фазы.
 *
 * Пружины здесь запрещены: строка, которая доезжает с отскоком,
 * читается как сбой, а в таблице их на экране полсотни.
 */
export function useRowMotion() {
  const still = useReducedMotion()
  return {
    layout: !still,
    transition: { duration: still ? 0 : DURATION.slow, ease: EASE },
  } as const
}
